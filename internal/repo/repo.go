// Package repo manages bare repositories of metagit projects.
package repo

import (
	"context"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/ekalinin/metagit/internal/gitcmd"
)

// ErrInvalidName is returned for project names that are not allowed.
var ErrInvalidName = errors.New("project name may contain only a-z, 0-9, '.', '_' and '-', must not start with '.' or '-' and must be at most 100 characters")

// ErrExists is returned when the repository directory already exists.
var ErrExists = errors.New("repository already exists")

var nameRe = regexp.MustCompile(`^[a-z0-9_][a-z0-9._-]{0,99}$`)

// ValidateName checks a project name.
func ValidateName(name string) error {
	if !nameRe.MatchString(name) {
		return ErrInvalidName
	}
	return nil
}

// Manager creates and removes repositories.
type Manager struct {
	// ReposDir contains <project>.git directories.
	ReposDir string
	// HooksDir is set as core.hooksPath of every repository.
	HooksDir string
	Git      *gitcmd.Runner
}

// Path returns the repository directory of a project.
func (m *Manager) Path(name string) string {
	return filepath.Join(m.ReposDir, name+".git")
}

// Exists reports whether the repository of a project exists.
func (m *Manager) Exists(name string) bool {
	info, err := os.Stat(m.Path(name))
	return err == nil && info.IsDir()
}

// Create makes an empty bare repository configured for metagit.
func (m *Manager) Create(ctx context.Context, name string) (err error) {
	if err := ValidateName(name); err != nil {
		return err
	}
	path := m.Path(name)
	if _, err := os.Stat(path); err == nil {
		return ErrExists
	} else if !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	if err := os.MkdirAll(m.ReposDir, 0o700); err != nil {
		return err
	}
	defer func() {
		if err != nil {
			_ = os.RemoveAll(path)
		}
	}()
	if _, err := m.Git.Run(ctx, gitcmd.Opts{Dir: m.ReposDir}, "init", "--bare", "-q", "-b", "main", path); err != nil {
		return err
	}
	return m.Configure(ctx, name)
}

// Configure (re)applies metagit settings to an existing repository.
func (m *Manager) Configure(ctx context.Context, name string) error {
	settings := [][2]string{
		{"core.hooksPath", m.HooksDir},
		// The reflog keeps old objects alive until they are archived.
		{"core.logAllRefUpdates", "always"},
	}
	for _, kv := range settings {
		if _, err := m.Git.Run(ctx, gitcmd.Opts{Dir: m.Path(name)}, "config", kv[0], kv[1]); err != nil {
			return err
		}
	}
	return nil
}

// Delete removes the repository of a project.
func (m *Manager) Delete(name string) error {
	if err := ValidateName(name); err != nil {
		return err
	}
	return os.RemoveAll(m.Path(name))
}

// ShellQuote quotes s for /bin/sh.
func ShellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// WriteScript writes an executable /bin/sh script that runs binary with args
// and passes through its own arguments.
func WriteScript(path, binary string, args ...string) error {
	var b strings.Builder
	b.WriteString("#!/bin/sh\n# Generated by metagit on every start. Do not edit.\nexec ")
	b.WriteString(ShellQuote(binary))
	for _, a := range args {
		b.WriteString(" ")
		b.WriteString(ShellQuote(a))
	}
	b.WriteString(" \"$@\"\n")
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(b.String()), 0o755); err != nil {
		return err
	}
	if err := os.Chmod(tmp, 0o755); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// HookNames are the git hooks metagit installs.
var HookNames = []string{"pre-receive", "post-receive"}

// WriteHooks writes hook scripts that call "<binary> hook <name>".
func WriteHooks(hooksDir, binary string) error {
	for _, name := range HookNames {
		if err := WriteScript(filepath.Join(hooksDir, name), binary, "hook", name); err != nil {
			return fmt.Errorf("write hook %s: %w", name, err)
		}
	}
	return nil
}
